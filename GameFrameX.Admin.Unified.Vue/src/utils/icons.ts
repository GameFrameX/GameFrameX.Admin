// Centralized FA 6 icon exports — import from here instead of @fortawesome directly
// Used by el-button :icon="faXxx" and other component-level icon bindings
// Each export is a Vue component wrapping FontAwesomeIcon

import {h, defineComponent} from 'vue';
import {FontAwesomeIcon} from '@fortawesome/vue-fontawesome';
import type {IconDefinition} from '@fortawesome/fontawesome-svg-core';

function wrap(icon: IconDefinition) {
  return defineComponent({
    render() {
      return h(FontAwesomeIcon, {icon});
    },
  });
}

